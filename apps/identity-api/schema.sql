CREATE TABLE IF NOT EXISTS identity_accounts (
    id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
    email text NOT NULL UNIQUE,
    display_name text NOT NULL,
    password_hash text NOT NULL,
    role text NOT NULL CHECK (role IN ('user', 'operator'))
);

CREATE TABLE IF NOT EXISTS identity_challenges (
    purpose text NOT NULL CHECK (purpose IN ('verify', 'reset')),
    email text NOT NULL,
    token_hash bytea NOT NULL UNIQUE,
    expires_at timestamptz NOT NULL,
    PRIMARY KEY (purpose, email)
);

ALTER TABLE identity_challenges
    ADD COLUMN IF NOT EXISTS token_nonce bytea,
    ADD COLUMN IF NOT EXISTS legacy_token_hash bytea,
    ADD COLUMN IF NOT EXISTS legacy_expires_at timestamptz;

CREATE UNIQUE INDEX IF NOT EXISTS identity_challenges_legacy_hash_idx
    ON identity_challenges (legacy_token_hash) WHERE legacy_token_hash IS NOT NULL;

CREATE TABLE IF NOT EXISTS identity_sessions (
    token_hash bytea PRIMARY KEY,
    account_id uuid NOT NULL REFERENCES identity_accounts(id) ON DELETE CASCADE,
    expires_at timestamptz NOT NULL
);

CREATE INDEX IF NOT EXISTS identity_sessions_account_idx ON identity_sessions (account_id);

CREATE TABLE IF NOT EXISTS identity_mail_requests (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    purpose text NOT NULL CHECK (purpose IN ('verify', 'reset')),
    email text NOT NULL,
    attempts integer NOT NULL DEFAULT 0,
    created_at timestamptz NOT NULL DEFAULT now(),
    next_at timestamptz NOT NULL DEFAULT now(),
    UNIQUE (purpose, email)
);

ALTER TABLE identity_mail_requests ADD COLUMN IF NOT EXISTS challenge_hash bytea;

CREATE INDEX IF NOT EXISTS identity_mail_requests_pending_idx ON identity_mail_requests (next_at, id);

CREATE TABLE IF NOT EXISTS identity_rate_limits (
    key text PRIMARY KEY,
    hits integer NOT NULL,
    expires_at timestamptz NOT NULL
);
